const quote = value => `"${String(value).replaceAll('"', '""')}"`;
export const exampleCsv = work => '\uFEFF配件,参考数量,备注\r\n' + work.bom.map(part => [part.name, part.quantity, part.note].map(quote).join(',')).join('\r\n') + '\r\n';

function example(id, title, category, image, summary, description, bom) {
  const work = {
    id: `official-${id}`, title, category, author: '造物所官方概念', summary,
    description: `${description}\n\n这是造物所的概念灵感示例，图片为 AI 生成的外观示意，配件表仅供构思参考。结构、电路、尺寸和安全性尚未实测；正式制作前请自行核对。`,
    bom: bom.map(([name, quantity, note = '型号与尺寸待验证']) => ({ name, quantity, note })),
    coverUrl: `/assets/market-${image}.png`, coverFileId: 'cover', isExample: true,
    createdAt: '2026-10-06T00:00:00.000Z',
  };
  work.files = [{ id: 'bom', name: `${title}-概念配件表.csv`, type: 'text/csv', extension: 'csv', size: Buffer.byteLength(exampleCsv(work), 'utf8') }];
  return work;
}

